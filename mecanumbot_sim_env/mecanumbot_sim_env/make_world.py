"""Build a Gazebo world from a Nav2 map, so the simulator and the map always agree.

Every occupied pixel becomes part of a wall. Neighbouring pixels are merged
into as few boxes as possible (row runs first, then stacked rows), which keeps
the world small enough to load quickly. Unknown space is left empty.

World coordinates are map coordinates, so with exact odometry the robot's
odom frame lines up with the map frame.

    ros2 run mecanumbot_sim_env make_world maps/AI_dept/AI_dept.yaml > AI_dept.sdf
"""

import argparse
import os

import numpy as np
from PIL import Image
import yaml

WORLD_TEMPLATE = """<?xml version="1.0" ?>
<!-- Generated by mecanumbot_sim_env/make_world.py from {map_name}. Do not edit by hand. -->
<sdf version="1.9">
  <world name="{world_name}">
    <physics name="4ms" type="ignored">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.8 0.8 0.8 1</background>
      <grid>false</grid>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          <material><ambient>0.85 0.85 0.85 1</ambient><diffuse>0.85 0.85 0.85 1</diffuse></material>
        </visual>
      </link>
    </model>

    <model name="walls">
      <static>true</static>
      <link name="link">
{boxes}
      </link>
    </model>
  </world>
</sdf>
"""

BOX_TEMPLATE = """        <collision name="c{index}">
          <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>
          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
        </collision>
        <visual name="v{index}">
          <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>
          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
          <material><ambient>0.45 0.45 0.5 1</ambient><diffuse>0.45 0.45 0.5 1</diffuse></material>
        </visual>"""


def load_occupied(map_yaml):
    """True where the map is occupied, following map_server's trinary thresholds."""
    with open(map_yaml) as stream:
        meta = yaml.safe_load(stream)
    image = Image.open(os.path.join(os.path.dirname(map_yaml), meta['image'])).convert('L')
    pixels = np.asarray(image, dtype=float) / 255.0
    occupancy = pixels if meta.get('negate', 0) else 1.0 - pixels
    return occupancy > meta['occupied_thresh'], meta


def merge_rectangles(mask):
    """Cover the True cells with axis-aligned rectangles (row, col, rows, cols)."""
    rectangles = []
    open_runs = {}  # (col_start, col_end) -> [row_start, rows]
    for row in range(mask.shape[0] + 1):
        runs = set()
        if row < mask.shape[0]:
            line = np.concatenate(([False], mask[row], [False]))
            edges = np.flatnonzero(line[1:] != line[:-1])
            runs = {(int(start), int(end)) for start, end in zip(edges[::2], edges[1::2])}
        for run in list(open_runs):
            if run in runs:
                open_runs[run][1] += 1
            else:
                row_start, rows = open_runs.pop(run)
                rectangles.append((row_start, run[0], rows, run[1] - run[0]))
        for run in runs:
            open_runs.setdefault(run, [row, 1])
    return rectangles


def world_sdf(map_yaml, wall_height=0.5, world_name=None):
    occupied, meta = load_occupied(map_yaml)
    resolution = meta['resolution']
    origin_x, origin_y = meta['origin'][:2]
    if len(meta['origin']) > 2 and meta['origin'][2]:
        raise SystemExit('rotated map origins are not supported')
    height = occupied.shape[0]
    map_name = os.path.splitext(os.path.basename(map_yaml))[0]

    boxes = []
    for index, (row, col, rows, cols) in enumerate(merge_rectangles(occupied)):
        boxes.append(BOX_TEMPLATE.format(
            index=index,
            x=origin_x + (col + cols / 2.0) * resolution,
            y=origin_y + (height - row - rows / 2.0) * resolution,
            z=wall_height / 2.0,
            sx=cols * resolution, sy=rows * resolution, sz=wall_height,
        ))
    return WORLD_TEMPLATE.format(
        map_name=map_name, world_name=world_name or map_name, boxes='\n'.join(boxes))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('map_yaml')
    parser.add_argument('--wall-height', type=float, default=0.5)
    parser.add_argument('--name', help='World name (default: map name)')
    args = parser.parse_args()
    print(world_sdf(args.map_yaml, args.wall_height, args.name))


if __name__ == '__main__':
    main()
